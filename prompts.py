# 场景映射字典
PROMPT_MAP = {
    "chat": CHAT_SYSTEM_PROMPT,
    "callcenter": CALLCENTER_SYSTEM_PROMPT,
    "dst": DST_SYSTEM_PROMPT,
    "tech_support": TECH_SUPPORT_PROMPT,
    "education": EDUCATION_PROMPT,
}

# 默认提示词
DEFAULT_PROMPT = CHAT_SYSTEM_PROMPT


def get_prompt(scenario: str = "chat") -> str:
    """
    获取指定场景的系统提示词
    
    Args:
        scenario: 场景名称，可选值：chat, callcenter, dst, tech_support, education
        
    Returns:
        对应场景的系统提示词
    """
    return PROMPT_MAP.get(scenario, DEFAULT_PROMPT)


