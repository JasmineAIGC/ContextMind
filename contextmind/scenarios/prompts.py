# 场景映射字典（用于按名称查找提示词）
PROMPT_MAP = {
    "chat": CHAT_SYSTEM_PROMPT,
    "callcenter": CALLCENTER_SYSTEM_PROMPT,
    "insurance": INSURANCE_SYSTEM_PROMPT,
}

# 默认提示词
DEFAULT_PROMPT = CHAT_SYSTEM_PROMPT


def get_prompt(scenario: str = "chat") -> str:
    """
    获取指定场景的系统提示词。

    Args:
        scenario: 场景名称，支持：chat、callcenter、insurance。
                  传入未知场景名时回退到默认提示词（chat）。

    Returns:
        对应场景的系统提示词；未匹配时返回 CHAT_SYSTEM_PROMPT。
    """
    return PROMPT_MAP.get(scenario, DEFAULT_PROMPT)


