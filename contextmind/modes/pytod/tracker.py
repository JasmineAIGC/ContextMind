class AdkPyTODTracker:
    """基于 AdkLLMClient 的 PyTOD 三步流程追踪器。

    实现论文 "Task-Oriented Dialogue as Dataflow Synthesis" 中的三步流程：
    - Step 1 AP（动作解析器）：LLM 根据对话历史和 Schema 生成 Python-like 程序
    - Step 2 EE（执行引擎）：ExecutionEngine 安全解析并执行程序，填充变量值
    - Step 3 DM（对话管理器）：LLM 根据执行结果生成自然语言回复

    LLM 后端统一使用 AdkLLMClient（或任何实现 ``chat_async()`` 的客户端），
    不依赖 ADK 原生 Function Calling（LlmAgent / InMemoryRunner / FunctionTool）。

    参数
    ----
    llm_client : Any
        实现 ``chat_async(messages: List[dict]) -> str`` 的 LLM 客户端
        （如 ``AdkLLMClient``）。
    engine : ExecutionEngine
        已注册 API 函数的执行引擎。
    schema : ServiceSchema | None
        服务 Schema，约束 AP 阶段可生成的意图和槽位。
        为 None 时使用空 Schema（开放域模式）。
    scenario_context : str
        业务场景描述，嵌入 AP 和 DM 的 system prompt。
    max_history_turns : int
        AP/DM prompt 中保留的最近历史轮次数。
    """

    # 意图数量超过此阈值时自动启用 top-K 过滤，避免全量 API 注入超出上下文窗口
    _AUTO_TOP_K_THRESHOLD: int = 20
    # 自动启用时使用的默认 K 值
    _AUTO_TOP_K_DEFAULT: int = 15

    def __init__(
        self,
        llm_client: Any,
        engine: ExecutionEngine,
        schema: Optional[ServiceSchema] = None,
        scenario_context: str = "",
        max_history_turns: int = 10,
        compact_schema: bool = False,
        top_k_intents: int = 0,
    ) -> None:
        self.llm_client = llm_client
        self.engine = engine
        self.schema = schema or ServiceSchema(service_name="default", description="")
        self.scenario_context = scenario_context

        # 自动启用 top-K 过滤：当 top_k_intents == 0（默认/未指定）且意图数量超过阈值时，
        # 自动设定 top_k_intents = _AUTO_TOP_K_DEFAULT，防止全量 API 列表撑爆上下文窗口。
        n_intents = len(self.schema.intents) if self.schema.intents else 0
        if top_k_intents == 0 and n_intents > self._AUTO_TOP_K_THRESHOLD:
            top_k_intents = self._AUTO_TOP_K_DEFAULT
            logger.info(
                f"AdkPyTODTracker: schema 含 {n_intents} 个意图（> {self._AUTO_TOP_K_THRESHOLD}），"
                f"自动启用 top_k_intents={top_k_intents} 以避免上下文溢出"
            )

        # top_k_intents > 0: 每轮只把最相关的 top_k_intents 个 API 函数放入 AP prompt
        # top_k_intents == 0: 原有行为，展示全部 API（向后兼容）
        self.top_k_intents: int = top_k_intents

        # 构建 {intent_name: signature_line} 映射，供 per-turn 过滤时快速查询函数签名
        intent_sig_map: Dict[str, str] = {}
        for name in engine.list_functions():
            sig = engine.get_function_signature(name) or f"{name}(...)"
            intent_sig_map[name] = sig

        # top-K 过滤模式下，系统指令中省略函数签名（改为每轮动态注入用户消息），
        # 以保持系统消息尽可能短（有利于 KV-cache 复用）。
        # 全量模式下沿用原有行为（函数签名放入系统指令）。
        api_signatures_for_system = (
            "" if top_k_intents > 0 else engine.to_prompt_text(compact=compact_schema)
        )

        self.prompt_builder = PyTODPromptBuilder(
            schema=self.schema,
            api_signatures=api_signatures_for_system,
            max_history_turns=max_history_turns,
            compact_schema=compact_schema,
            intent_sig_map=intent_sig_map,
        )
        self._history: List[ConversationTurn] = []
        self.current_state: Dict[str, Any] = {}
        self.api_call_log: List[Dict[str, Any]] = []
        # Maps each variable name to the call-line that produced it, e.g.
        # "x4" → "inquire_amount_discrepancy(date='七月二十三号')".
        # Included in the AP prompt so the LLM can see which function produced
        # each prior variable and avoid redundant duplicate calls.
        self.var_call_sources: Dict[str, str] = {}
        self.turn_count: int = 0
        self.last_program_text: str = ""   # 最近一轮 AP 生成的程序（供 web_demo 展示）
        self.last_execution_result: Optional[Any] = None  # 最近一轮 EE 执行结果（供 web_demo 展示）
        # AP / DM 完整输入消息——供 trace_demo 记录每步实际发送给 LLM 的内容
        self.last_ap_messages: List[Dict[str, str]] = []
        self.last_dm_messages: List[Dict[str, str]] = []
        # 各步骤耗时（web_demo 的 timing_breakdown 会合并此字典）
        self.step_timings: Dict[str, float] = {}
        # 全局变量计数器——与官方 PyTOD 对齐：变量编号跨轮累积（x1, x2, …），
        # 使 AP 能在后续轮次中通过 xN.field 引用先前已计算的变量。
        self._next_var_index: int = 1

        self._ap_runner: Optional[Any] = None
        self._ap_session_id: Optional[str] = None
        self._dm_runner: Optional[Any] = None
        self._dm_session_id: Optional[str] = None

        if llm_client is not None:
            adk_model = create_local_adk_model(
                getattr(llm_client, "_config", None)
            )
            # AP Agent 静态系统指令 = AP 语法规则 [+ 全量函数签名（仅全量模式）]
            # top-K 过滤模式下，函数签名已从系统指令移除，改为每轮动态注入用户消息。
            if top_k_intents > 0:
                # 系统指令只保留语法规则，不含函数签名
                ap_instruction = self.prompt_builder._AP_SYSTEM
            else:
                # 全量模式（原有行为）：系统指令含全量函数签名
                ap_instruction = (
                    self.prompt_builder._AP_SYSTEM
                    + "\n\n"
                    + self.prompt_builder._build_api_signatures()
                )
            if scenario_context:
                ap_instruction += f"\n\n## 业务场景背景\n{scenario_context}"
            ap_agent = LlmAgent(
                name="pytod_ap",
                model=adk_model,
                instruction=ap_instruction,
            )
            self._ap_runner = InMemoryRunner(
                agent=ap_agent,
                app_name="contextmind_pytod_ap",
            )

            # DM Agent：静态系统指令 = DM 回复规则 + 语言要求
            dm_instruction = self.prompt_builder._DM_SYSTEM
            if scenario_context:
                dm_instruction += f"\n\n## 业务场景背景\n{scenario_context}"
            dm_instruction += f"\n\n请用{self.prompt_builder.response_language}回复。"
            dm_agent = LlmAgent(
                name="pytod_dm",
                model=adk_model,
                instruction=dm_instruction,
            )
            self._dm_runner = InMemoryRunner(
                agent=dm_agent,
                app_name="contextmind_pytod_dm",
            )
            logger.info(
                "[PyTOD] ADK LlmAgent+Runner 已初始化 (AP runner + DM runner), "
                "使用 ADK 原生会话管理"
            )

        logger.info(
            f"AdkPyTODTracker 初始化完成 (schema={self.schema.service_name}, "
            f"APIs: {engine.list_functions()})"
        )

    @classmethod
    def from_scenario(
        cls,
        llm_client: Any,
        scenario_config: Any,
        config: Optional[Any] = None,  # noqa: ARG003 — 保持与旧接口兼容
        **kwargs: Any,
    ) -> "AdkPyTODTracker":
        """从场景配置创建 AdkPyTODTracker。

        自动注册场景 API、加载 ServiceSchema 并填充场景描述。
        所有 Schema 和 API 均通过外部文件传入，PyTOD 不再内置场景数据。

        Args:
            llm_client:      LLM 客户端（如 ``AdkLLMClient``）。
            scenario_config: ScenarioConfig 实例。
            config:          保留参数，已忽略（兼容旧接口）。
            **kwargs:        传递给 ``__init__`` 的额外参数（如 ``max_history_turns``）。
                             特殊 key:
                             - ``schema`` (ServiceSchema): 外部传入的 schema 对象（必须提供）。
                             - ``schema_path`` (str|Path): schema.json 路径，用于自动
                               加载 companion ``*_pytod_apis.py`` 文件中的预生成函数。
                               若仅传 ``schema`` 而不传 ``schema_path``，则退化为存根模式。
        """
        # 过滤历史遗留的不兼容参数
        kwargs.pop("prompt_builder", None)
        kwargs.pop("app_name", None)
        kwargs.pop("user_id", None)

        # 外部 schema 优先取出，决定 API 注册策略
        external_schema = kwargs.pop("schema", None)
        # schema_path 用于自动加载 companion *_pytod_apis.py 文件
        schema_path: Optional[Any] = kwargs.pop("schema_path", None)

        # 加载预生成的 API 函数（来自 *_pytod_apis.py companion 文件）
        api_funcs: Optional[Dict[str, Any]] = None
        if schema_path is not None:
            api_funcs = load_pytod_api_module(schema_path)

        engine = ExecutionEngine()
        scenario_name = getattr(scenario_config, "name", "")

        if external_schema is not None:
            # 外部 schema 传入：从 schema 中的意图注册 API 函数（companion 文件优先）
            _register_apis_from_schema(
                engine, external_schema, replace_existing=True, api_funcs=api_funcs
            )
            schema = external_schema
        elif api_funcs:
            # 未提供 schema.json，但已从 *_pytod_apis.py 加载了真实 API 函数：
            # 从函数签名和 docstring 推导最小化 ServiceSchema，直接注册 API 函数。
            # 这样即使没有对应的 schema.json，AP 也能看到函数签名和意图描述。
            import inspect as _inspect
            synthetic_intents: List[IntentDefinition] = []
            for func_name, func in api_funcs.items():
                sig = _inspect.signature(func)
                all_params = [p for p in sig.parameters]
                synthetic_intents.append(IntentDefinition(
                    name=func_name,
                    description=(func.__doc__ or func_name).strip().split("\n")[0],
                    required_slots=[],
                    optional_slots=all_params,
                    result_slots=[],
                ))
            schema = ServiceSchema(
                service_name=scenario_name or "api_functions",
                description="从 pytod_apis.py 文件推导的服务 Schema",
                intents=synthetic_intents,
            )
            _register_apis_from_schema(
                engine, schema, replace_existing=True, api_funcs=api_funcs
            )
            logger.info(
                f"AdkPyTODTracker: 场景 '{scenario_name}' 已从 pytod_apis 文件推导 schema，"
                f"注册 {len(api_funcs)} 个 API 函数。"
            )
        else:
            # 未提供外部 schema 也未加载 api_funcs：空引擎（开放域模式）
            logger.warning(
                f"AdkPyTODTracker: 场景 '{scenario_name}' 未传入 schema，"
                "使用空引擎运行（AP 将无法引用业务 API）。"
                "请通过 schema= 参数传入 ServiceSchema 对象，"
                "或通过 schema_path= 指向 *_pytod_apis.py 或 schema/*_schema.json 文件。"
            )
            schema = None

        scenario_context = kwargs.pop(
            "scenario_context",
            getattr(scenario_config, "description", ""),
        )
        return cls(
            llm_client=llm_client,
            engine=engine,
            schema=schema,
            scenario_context=scenario_context,
            **kwargs,
        )

    async def process_turn(
        self,
        user_utterance: str,
        system_utterance: str = "",
    ) -> Dict[str, Any]:
        """执行一轮三步对话处理（AP → EE → DM）。

        Returns:
            包含以下键的字典：

            - ``response`` (str): DM 生成的自然语言回复。
            - ``program_text`` (str): AP 生成的 PyTOD 程序文本。
            - ``state`` (dict): 本轮后的累积状态（变量值快照）。
            - ``execution`` (ProgramExecutionResult): EE 执行结果。

            ``step_timings`` 属性同步更新为各步骤耗时（供 web_demo 使用）。
        """
        self.turn_count += 1
        logger.info(f"AdkPyTODTracker 第 {self.turn_count} 轮 | AP→EE→DM | 用户: {user_utterance}")
        self.step_timings = {}

        # 外呼场景：首轮前系统主动发起的话语（如"您好，请问是李明先生吗？"），
        # 注入对话历史，使 AP 能感知用户回复所针对的上下文。
        # 仅在历史为空时注入，避免重复（后续轮次的系统话语已由上一轮 DM 写入）。
        if system_utterance and not self._history:
            self._history.append(ConversationTurn(role="assistant", content=system_utterance))
            logger.debug(f"[AdkPyTODTracker] 注入系统发起语到历史: {system_utterance[:80]}")

        # ------------------------------------------------------------------ #
        # Step 1: Action Parser (AP)
        # ------------------------------------------------------------------ #
        t0 = time.time()
        # 向 AP 传入先前轮次的已计算变量（官方 PyTOD dataflow context）。
        # 过滤规则：以 "_anon" 开头的匿名变量不注入（无意义的裸调用）。
        # 注意：schema 存根值（{"status":"success","intent":"..."}）仍包含在内，
        # 但在 _format_prior_dataflow 中以 "[已完成，无可引用数据]" 标注，
        # 让 AP 知道该 API 已被调用过、无需重复，同时不会误导 AP 引用无意义字段。
        prior_dataflow = {
            k: v for k, v in self.current_state.items()
            if not k.startswith("_anon")
        }

        # top-K 意图检索：当 top_k_intents > 0 时，对所有意图做多信号 TF-IDF 打分，
        # 只把最相关的 top_k_intents 个 API 放入本轮 AP prompt。
        # top_k_intents == 0 时保持原有全量行为。
        relevant_intent_names: Optional[List[str]] = None
        if self.top_k_intents > 0 and self.schema.intents:
            # ── 构建多轮查询文本 ────────────────────────────────────────────
            # 取最近3条用户历史（含当前话语），扩大语义召回范围。
            # 越近的轮次语义相关性越高，直接拼接（set-based 评分天然避免重复计数）。
            query_parts = [user_utterance]
            user_count = 0
            for turn in reversed(self._history):
                if turn.role == "user":
                    query_parts.append(turn.content)
                    user_count += 1
                    if user_count >= 2:   # 最多取2条历史用户话语
                        break
            query_text = " ".join(query_parts)

            # ── 提取已调用 API 名称（用于已调用意图降权）──────────────────
            # var_call_sources: {"x1": "query_balance(account='123')", ...}
            already_called: Set[str] = set()
            for call_str in self.var_call_sources.values():
                m = re.match(r"^([A-Za-z_]\w*)\s*\(", call_str)
                if m:
                    already_called.add(m.group(1))

            relevant_intent_names = _score_intents_for_query(
                self.schema.intents, query_text, self.top_k_intents,
                already_called_names=already_called,
            )
            logger.debug(
                f"[AP top-K] 查询={query_text[:80]!r} | "
                f"已调用={already_called} | "
                f"相关意图({len(relevant_intent_names)}/{len(self.schema.intents)}): "
                f"{relevant_intent_names}"
            )

        ap_messages = self.prompt_builder.build_action_parser_prompt(
            self._history,
            user_utterance,
            self.scenario_context,
            prior_dataflow=prior_dataflow or None,
            next_var_index=self._next_var_index,
            call_sources=self.var_call_sources,
            relevant_intent_names=relevant_intent_names,
        )
        self.last_ap_messages = ap_messages        # 记录完整 AP 输入（供 trace_demo 保存）

        if self._ap_runner is not None:
            # ---------------------------------------------------------- #
            # ADK 路径：AP LlmAgent 通过 InMemoryRunner 生成程序文本
            # ADK session 积累 (用户输入 → 程序) 历史，AP 自然感知变量上下文
            # ---------------------------------------------------------- #
            # 构建 AP 的用户消息：动态部分（history + API签名/意图描述 + 当前话语 + 约束）
            # 全量模式下，API签名在 LlmAgent.instruction 中（静态）；意图描述在此动态注入。
            # top-K 过滤模式下，筛选后的 API 签名也在此动态注入（系统指令不含函数列表）。
            from contextmind.modes.pytod.prompts import _format_prior_dataflow as _fmt_df
            ap_user_parts = []
            if self._history:
                history_str = self.prompt_builder._format_history(self._history)
                ap_user_parts.append(f"## 对话历史\n{history_str}")
            # top-K 过滤模式：将筛选后的 API 签名注入用户消息（替代系统指令中的全量列表）
            if relevant_intent_names is not None:
                filtered_sigs = self.prompt_builder._build_api_signatures(relevant_intent_names)
                if filtered_sigs:
                    ap_user_parts.append(filtered_sigs)
            # 意图描述：每轮动态注入（compact_schema=True 时为空；top-K 模式下按相关意图过滤）
            intent_ctx = self.prompt_builder._build_intent_context(relevant_intent_names)
            if intent_ctx:
                ap_user_parts.append(intent_ctx)
            # 已计算变量：含调用来源行，帮助 AP 识别重复调用
            dataflow_section = _fmt_df(
                prior_dataflow or None,
                self._next_var_index,
                call_sources=self.var_call_sources,
            )
            if dataflow_section:
                ap_user_parts.append(dataflow_section.strip())
            else:
                if self._next_var_index > 1:
                    ap_user_parts.append(
                        f"## 新变量编号约束\n本轮新变量从 x{self._next_var_index} 开始，"
                        f"不得使用 x1~x{self._next_var_index - 1}"
                    )
            ap_user_parts.append(f"## 当前用户话语\n{user_utterance}\n\n请生成 PyTOD 程序：")
            ap_user_message = "\n\n".join(ap_user_parts)
            program_text = await self._run_adk_ap(ap_user_message)
        else:
            program_text = await self.llm_client.chat_async(ap_messages)
            # 剥除 LLM 可能输出的 markdown 代码块包裹
            program_text = re.sub(r"```[^\n]*\n?", "", program_text).strip()

        self.last_program_text = program_text   # 记录供 web_demo 展示
        self.step_timings["AP (动作解析)"] = round(time.time() - t0, 3)
        logger.info(f"[AP] 程序: {program_text[:150]}")

        # ------------------------------------------------------------------ #
        # Step 2: Execution Engine (EE)
        # ------------------------------------------------------------------ #
        t1 = time.time()
        execution_result: ProgramExecutionResult = self.engine.execute_program(
            program_text,
            prior_var_values={
                k: v for k, v in self.current_state.items()
                if not k.startswith("_anon") and not _is_stub_only_result(v)
            },
        )
        self.last_execution_result = execution_result  # 记录供 web_demo 展示
        self.step_timings["EE (执行引擎)"] = round(time.time() - t1, 3)

        # 更新 var_call_sources：记录本轮程序中每个变量绑定的调用来源，
        # 供后续轮次 AP 提示词显示（帮助 AP 避免重复调用相同函数）。
        self.var_call_sources.update(_extract_var_call_sources(program_text))

        # 将本轮 API 调用结果合并进累积状态，并记录调用日志。
        # 仅存储真正的 API 调用结果（dict/非字符串），跳过 say() 输出的字符串变量，
        # 避免 prior_dataflow 随轮次膨胀，减少后续轮次 AP 的 token 消耗。
        if execution_result.variable_values:
            for var, val in execution_result.variable_values.items():
                if var in execution_result.say_variable_names:
                    continue  # say() 输出不写入 current_state
                self.current_state[var] = val
                self.api_call_log.append({
                    "turn": self.turn_count,
                    "variable": var,
                    "result": val,
                })
        if not execution_result.success:
            logger.warning(f"[EE] 执行错误: {execution_result.errors}")
        else:
            called = list(execution_result.variable_values.keys())
            say_preview = execution_result.say_output[:60] if execution_result.say_output else "(无)"
            logger.info(f"[EE] 执行成功: APIs={called}, say={say_preview!r}")

        # 推进全局变量计数器（与官方 PyTOD 对齐：变量编号跨轮连续递增）。
        # 取最大 N+1 作为下一轮起始编号；保证单调递增——即使 AP 生成了旧编号
        # （违反提示），_next_var_index 也不会后退。
        var_indices = [int(m) for m in re.findall(r"\bx(\d+)\b", program_text)]
        if var_indices:
            self._next_var_index = max(self._next_var_index, max(var_indices) + 1)

        # ------------------------------------------------------------------ #
        # Step 3: Dialogue Manager (DM)
        # ------------------------------------------------------------------ #
        t2 = time.time()
        dm_messages = self.prompt_builder.build_dm_prompt(
            self._history, user_utterance, program_text, execution_result, self.scenario_context,
        )
        self.last_dm_messages = dm_messages             # 记录完整 DM 输入（供 trace_demo 保存）

        if self._dm_runner is not None:
            # ---------------------------------------------------------- #
            # ADK 路径：DM LlmAgent 通过 InMemoryRunner 生成自然语言回复
            # DM session 积累完整对话历史，保证回复连贯
            # ---------------------------------------------------------- #
            # 构建 DM 的用户消息：包含执行结果和用户话语
            dm_user_parts = []
            if execution_result.say_output:
                dm_user_parts.append(f"## AP 指定的 say 输出（必须在回复中体现）\n{execution_result.say_output}")
            if execution_result.hint_messages:
                dm_user_parts.append(f"## Hint 提示（需向用户询问的信息）\n" + "\n".join(execution_result.hint_messages))
            if not execution_result.success and execution_result.errors:
                dm_user_parts.append(f"## 执行错误\n" + "\n".join(execution_result.errors))
            dm_user_parts.append(f"## 用户话语\n{user_utterance}\n\n请生成回复：")
            dm_user_message = "\n\n".join(dm_user_parts)
            response = await self._run_adk_dm(dm_user_message)
        else:
            response = await self.llm_client.chat_async(dm_messages)

        self.step_timings["DM (对话管理)"] = round(time.time() - t2, 3)
        logger.info(f"[DM] 回复: {response[:150]}")

        # 更新对话历史
        self._history.append(ConversationTurn(role="user", content=user_utterance))
        self._history.append(ConversationTurn(role="assistant", content=response))

        return {
            "response": response,
            "program_text": program_text,
            "state": dict(self.current_state),
            "execution": execution_result,
        }

    def get_current_state(self) -> Dict[str, Any]:
        """返回当前累积对话状态（API 执行结果 + API 调用日志）。"""
        state = dict(self.current_state)
        if self.api_call_log:
            state["_api_call_log"] = list(self.api_call_log)
        return state

    def reset(self) -> None:
        """重置对话状态，开始新的会话。"""
        self._history = []
        self.current_state = {}
        self.api_call_log = []
        self.var_call_sources = {}
        self.turn_count = 0
        self.last_program_text = ""
        self.last_execution_result = None
        self.last_ap_messages = []
        self.last_dm_messages = []
        self.step_timings = {}
        self._next_var_index = 1
        # 重置 ADK 会话 ID（下次 process_turn 时自动重建新 session）
        self._ap_session_id = None
        self._dm_session_id = None
        logger.info("AdkPyTODTracker 对话状态已重置")

    async def _get_or_create_ap_session(self) -> str:
        """获取或创建 AP ADK 会话 ID。"""
        if self._ap_session_id is None:
            session = await self._ap_runner.session_service.create_session(
                app_name="contextmind_pytod_ap",
                user_id="default_user",
            )
            self._ap_session_id = session.id
        return self._ap_session_id

    async def _get_or_create_dm_session(self) -> str:
        """获取或创建 DM ADK 会话 ID。"""
        if self._dm_session_id is None:
            session = await self._dm_runner.session_service.create_session(
                app_name="contextmind_pytod_dm",
                user_id="default_user",
            )
            self._dm_session_id = session.id
        return self._dm_session_id

    async def _run_adk_ap(self, ap_user_message: str) -> str:
        """通过 ADK AP-LlmAgent 生成 PyTOD 程序文本。

        AP session 积累（用户输入 → 程序）历史，使 AP 能感知跨轮变量上下文。

        Args:
            ap_user_message: 当前轮次的 AP 输入（格式化历史 + 用户话语 + 约束）

        Returns:
            AP 生成的 PyTOD 程序文本（已剥除 markdown 代码块）
        """
        session_id = await self._get_or_create_ap_session()
        content = genai_types.Content(
            role="user",
            parts=[genai_types.Part(text=ap_user_message)],
        )
        program_text = ""
        async for event in self._ap_runner.run_async(
            user_id="default_user",
            session_id=session_id,
            new_message=content,
        ):
            if event.is_final_response() and event.content and event.content.parts:
                for part in event.content.parts:
                    if hasattr(part, "text") and part.text and not getattr(part, "thought", False):
                        program_text += part.text
        # 剥除 LLM 可能输出的 markdown 代码块包裹
        program_text = re.sub(r"```[^\n]*\n?", "", program_text).strip()
        return program_text

    async def _run_adk_dm(self, dm_user_message: str) -> str:
        """通过 ADK DM-LlmAgent 生成自然语言回复。

        DM session 积累完整对话历史，保证回复连贯。

        Args:
            dm_user_message: 当前轮次的 DM 输入（执行结果 + 用户话语）

        Returns:
            DM 生成的自然语言回复
        """
        session_id = await self._get_or_create_dm_session()
        content = genai_types.Content(
            role="user",
            parts=[genai_types.Part(text=dm_user_message)],
        )
        response_text = ""
        async for event in self._dm_runner.run_async(
            user_id="default_user",
            session_id=session_id,
            new_message=content,
        ):
            if event.is_final_response() and event.content and event.content.parts:
                for part in event.content.parts:
                    if hasattr(part, "text") and part.text and not getattr(part, "thought", False):
                        response_text += part.text
        return response_text.strip()
