"""
PyTOD Tracker — AdkPyTODTracker 实现（AP → EE → DM 三步流程）

严格遵循论文 "Task-Oriented Dialogue as Dataflow Synthesis"，
使用 Google ADK LlmAgent + InMemoryRunner 驱动 AP 和 DM 两个 LLM 步骤：

    Step 1  Action Parser (AP)：ADK LlmAgent 根据对话历史 + Schema 生成 Python-like 程序
    Step 2  Execution Engine (EE)：ExecutionEngine 安全解析并执行程序（纯 Python，无 LLM）
    Step 3  Dialogue Manager (DM)：ADK LlmAgent 根据执行结果生成自然语言回复

ADK 集成优势：
- AP 和 DM 各有独立 LlmAgent + InMemoryRunner，ADK 自动管理各步骤的会话历史
- AP session 积累（程序生成历史），使 AP 能感知跨轮次的变量上下文
- DM session 积累对话历史，保证回复自然、连贯

PyTOD 不在算法代码内部硬编码场景 Schema 和 API 数据。所有 Schema 均通过外部文件传入：
  1. 生成 companion 文件：``python examples/build_schema_data.py --schema schema/xxx_schema.json``
  2. 传入追踪器：``AdkPyTODTracker.from_scenario(..., schema=svc, schema_path="schema/xxx_schema.json")``

使用示例::

    from contextmind.modes.pytod import AdkPyTODTracker
    from contextmind.modes.pytod.schemas import load_schema_from_dict
    from contextmind.infra.llm_client import AdkLLMClient
    import json

    with open("schema/anyihua_schema.json") as f:
        svc = load_schema_from_dict(json.load(f))

    llm = AdkLLMClient()
    from contextmind.scenarios import get_anyihua_scenario
    config = get_anyihua_scenario()
    tracker = AdkPyTODTracker.from_scenario(
        llm, config, schema=svc, schema_path="schema/anyihua_schema.json"
    )
    result = await tracker.process_turn("查询我的账户余额")
    print(result["program_text"])
    print(result["response"])
"""

