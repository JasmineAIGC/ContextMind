def _tokenize_text(text: str) -> List[str]:
    """对文本做 token 化：汉字逐字 + 英文/数字词，过滤停用词和单字符（非汉字）token。"""
    tokens = []
    for tok in re.findall(r"[\u4e00-\u9fff]|\w+", text.lower()):
        if tok in _STOPWORDS:
            continue
        # 单字符英文/数字 token 通常无意义（如 "a", "b", "1"）
        if len(tok) == 1 and not ("\u4e00" <= tok <= "\u9fff"):
            continue
        tokens.append(tok)
    return tokens


def _split_identifier(name: str) -> List[str]:
    """将 snake_case / camelCase 标识符拆分为语义 token 列表。

    示例::

        "query_balance"       → ["query", "balance"]
        "verifyUserIdentity"  → ["verify", "user", "identity"]
        "account_id"          → ["account"]   # "id" 为单字符英文，过滤
    """
    # camelCase → snake_case 预处理
    name = re.sub(r"([A-Z])", r"_\1", name)
    parts = re.split(r"[_\s\-]+", name.lower())
    result = []
    for p in parts:
        if not p or p in _STOPWORDS:
            continue
        if len(p) == 1 and not ("\u4e00" <= p <= "\u9fff"):
            continue
        result.append(p)
    return result


def _build_intent_tokens(
    intent: "IntentDefinition",
) -> Dict[str, Set[str]]:
    """为意图构建按字段分组的 token 集合，用于加权评分。

    返回::

        {
          "name":  token set from function name,
          "desc":  token set from description,
          "slots": token set from required + optional slot names,
        }
    """
    name_tokens: Set[str] = set(_split_identifier(intent.name))
    desc_tokens: Set[str] = set(_tokenize_text(intent.description or ""))
    slot_tokens: Set[str] = set()
    for slot in list(intent.required_slots) + list(intent.optional_slots):
        slot_tokens.update(_split_identifier(slot))
    return {"name": name_tokens, "desc": desc_tokens, "slots": slot_tokens}


def _score_intents_for_query(
    intents: List["IntentDefinition"],
    query_text: str,
    top_k: int,
    already_called_names: Optional[Set[str]] = None,
) -> List[str]:
    """多信号 TF-IDF 风格意图评分，返回最相关的 top-K 意图名称。

    相比简单词袋方案的核心改进：

    1. **停用词过滤**：剔除中英文功能词（"我"、"的"、"is"、"a" 等），仅保留
       有语义内容的词，大幅降低噪音。
    2. **标识符分解**：将 snake_case / camelCase API 名拆分为语义子词（如
       "query_balance" → {"query", "balance"}），解决中文查询无法直接匹配
       英文 API 名的跨语言匹配问题。
    3. **分字段加权**：函数名命中（×3.0）> 描述命中（×2.0）> 槽位名命中（×1.5），
       反映了各字段的语义密度差异。
    4. **IDF 权重**：对所有意图文档统计词频，计算 IDF（log((N+1)/(df+1))+1），
       使稀有词（高区分度）得分更高，普遍词（低区分度）得分更低，与 BM25 原理一致。
    5. **已调用意图惩罚**：已成功调用的 API 得分乘以惩罚系数（默认 0.2），避免
       在 prior_dataflow 中已有结果的 API 占用 prompt 空间，但不完全排除（允许重试）。

    Args:
        intents:              所有注册意图列表（来自 ServiceSchema.intents）。
        query_text:           搜索查询文本（当前话语 + 近期历史拼接）。
        top_k:                最多返回的意图数量。
        already_called_names: 本对话中已成功调用过的 API 函数名集合，用于降权。

    Returns:
        长度 ≤ top_k 的意图名称列表，按相关性降序排列。
        若 top_k >= len(intents) 则直接返回全部意图名称（不过滤）。
    """
    if not intents or top_k <= 0 or top_k >= len(intents):
        return [intent.name for intent in intents]

    already_called: Set[str] = already_called_names or set()

    # ── 1. 查询 token 化 ──────────────────────────────────────────────────
    query_tokens: Set[str] = set(_tokenize_text(query_text))
    if not query_tokens:
        # 查询无有效 token（如纯标点/数字）→ 回退为前 top_k 个意图
        return [i.name for i in intents[:top_k]]

    # ── 2. 为每个意图构建分字段 token 集合 ───────────────────────────────
    intent_fields: Dict[str, Dict[str, Set[str]]] = {
        intent.name: _build_intent_tokens(intent) for intent in intents
    }

    # ── 3. 计算 IDF（基于所有意图文档的词频统计）────────────────────────
    term_doc_freq: Dict[str, int] = {}
    for fields in intent_fields.values():
        all_tokens = fields["name"] | fields["desc"] | fields["slots"]
        for tok in all_tokens:
            term_doc_freq[tok] = term_doc_freq.get(tok, 0) + 1
    n = len(intents)
    # IDF = log((N+1)/(df+1)) + 1  — 与 scikit-learn TfidfTransformer 默认公式一致
    idf: Dict[str, float] = {
        t: math.log((n + 1) / (df + 1)) + 1.0
        for t, df in term_doc_freq.items()
    }

    # ── 4. 计算每个意图的综合得分 ─────────────────────────────────────────
    # 字段权重：函数名 > 描述 > 槽位名
    _FIELD_WEIGHTS = {"name": 3.0, "desc": 2.0, "slots": 1.5}
    # 已调用意图的得分惩罚系数（保留召回但降低优先级）
    _CALLED_PENALTY = 0.2

    scores: List[Tuple[float, str]] = []
    for intent in intents:
        fields = intent_fields[intent.name]
        score = 0.0
        for field, weight in _FIELD_WEIGHTS.items():
            matched_tokens = query_tokens & fields[field]
            # 分字段 IDF 加权求和
            field_score = sum(idf.get(t, 1.0) for t in matched_tokens) * weight
            score += field_score
        # 已调用意图降权
        if intent.name in already_called:
            score *= _CALLED_PENALTY
        scores.append((score, intent.name))

    scores.sort(key=lambda x: -x[0])
    return [name for _, name in scores[:top_k]]


def load_pytod_api_module(schema_path: Union[str, Path]) -> Optional[Dict[str, Any]]:
    """从 ``*_pytod_apis.py`` companion 文件加载 PyTOD API 函数。

    支持两种输入方式：

    1. **直接传入 .py 文件路径**（推荐）：``path/to/foo_pytod_apis.py``，直接加载。
    2. **传入 schema.json 路径**（兼容旧接口）：``path/to/foo_schema.json``，
       自动推导对应的 ``path/to/foo_pytod_apis.py`` 并加载。

    companion 文件由 ``SchemaDataBuilder.build_pytod_apis()`` 预生成，
    包含每个 intent 对应的真实 Python 函数定义（含 result_slots 返回值），
    或通过 ``python examples/build_schema_data.py`` 批量生成后提交到版本控制。

    Returns:
        成功时返回字典 ``{func_name: callable}``，可直接注册到 ExecutionEngine；
        文件不存在或加载失败时返回 ``None``（调用方将降级为纯存根模式）。

    Example::

        # 推荐：直接传入 .py 文件
        api_funcs = load_pytod_api_module("schema/anyihua_pytod_apis.py")
        # 兼容：传入 schema.json，自动推导 .py 路径
        api_funcs = load_pytod_api_module("schema/anyihua_schema.json")
        # → {"verify_identity": <function verify_identity>, ...}
    """
    import importlib.util

    p = Path(schema_path)
    if p.suffix == ".py":
        # 直接 .py 文件路径 — strip "_pytod_apis" suffix (if present) for a clean module name
        apis_path = p
        stem = p.stem
        base = stem[: -len("_pytod_apis")] if stem.endswith("_pytod_apis") else stem
    else:
        # JSON schema 路径 → 推导 companion .py
        stem = p.stem
        base = stem[: -len("_schema")] if stem.endswith("_schema") else stem
        apis_path = p.parent / f"{base}_pytod_apis.py"
    if not apis_path.exists():
        logger.debug(f"[api_module] companion apis 文件不存在: {apis_path}")
        return None
    try:
        mod_name = f"_pytod_apis_{base}"
        spec = importlib.util.spec_from_file_location(mod_name, apis_path)
        if spec is None or spec.loader is None:
            raise ImportError(f"无法创建 module spec: {apis_path}")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
        # Collect only functions defined in this module (not imported callables).
        # Using __module__ check prevents imported typing aliases (Optional, Dict, Any)
        # and other callables from being registered as API functions, which would
        # cause unexpected TypeError when the AP accidentally calls them.
        raw_funcs = {
            name: obj
            for name, obj in vars(mod).items()
            if callable(obj)
            and not name.startswith("_")
            and getattr(obj, "__module__", None) == mod_name
        }
        # Validate each function with a no-arg test call to detect LLM-generated bugs
        # (e.g. a function body that calls a string variable raises
        # "TypeError: 'str' object is not callable").  All generated API functions
        # accept only keyword arguments with default=None, so a zero-arg call is safe
        # and representative.  Functions that raise any exception are excluded so the
        # engine falls back to a stub instead of propagating a runtime error later.
        funcs: dict = {}
        for name, obj in raw_funcs.items():
            try:
                obj()
                funcs[name] = obj
            except Exception as exc:  # noqa: BLE001
                logger.warning(
                    f"[api_module] 函数 '{name}' 测试调用失败（将使用存根替代）: "
                    f"{type(exc).__name__}: {exc}"
                )
        if len(funcs) < len(raw_funcs):
            skipped = len(raw_funcs) - len(funcs)
            logger.warning(
                f"[api_module] {skipped} 个函数因测试调用失败而跳过，将使用存根替代"
            )
        logger.info(f"[api_module] 已加载 PyTOD API 函数: {apis_path} ({len(funcs)} 个函数)")
        return funcs
    except Exception as exc:
        logger.warning(f"[api_module] 加载 APIs 模块失败: {apis_path} — {exc}")
        return None


def _register_apis_from_schema(
    engine: ExecutionEngine,
    schema: ServiceSchema,
    replace_existing: bool = True,
    api_funcs: Optional[Dict[str, Any]] = None,
) -> None:
    """根据 ServiceSchema 的意图定义，在 ExecutionEngine 中注册对应的 API 函数。

    当外部 schema.json 传入时，用来补充或替换场景 API，确保 ExecutionEngine
    能够执行 AP 依据外部 Schema 生成的程序（意图名和槽位名与 schema 一致）。

    注册规则：
    - 若提供了 ``api_funcs``（由 ``load_pytod_api_module()`` 加载的预生成函数），
      则直接注册这些真实函数（含 result_slots 返回值），AP 可通过 ``say(xN.field)``
      引用结果字段。
    - 否则退化为存根模式：为每个 intent 注册接受 required+optional slots 的
      直通函数（无参调用时返回默认成功标记），仅用于保证 EE 不报错。

    Args:
        engine:           目标 ExecutionEngine。
        schema:           外部传入的 ServiceSchema。
        replace_existing: 为 True（默认）时先清空 registry 再注册，完全替换预定义函数；
                          为 False 时仅为 registry 中尚未注册的意图添加函数，
                          保留已有的预定义实现（具有真实业务逻辑的函数优先）。
        api_funcs:        可选的 ``{func_name: callable}`` 字典，通常通过
                          ``load_pytod_api_module(schema_path)`` 从预生成的
                          ``*_pytod_apis.py`` 文件加载。
    """
    import inspect

    if replace_existing:
        engine.registry.clear()

    schema_slot_names = [s.name for s in schema.slots]
    _funcs = api_funcs or {}

    def _make_stub_func(func_name: str, param_names: List[str]) -> Any:
        """为无预生成函数的意图创建存根（降级模式）。"""
        def _api(**kwargs: Any) -> Dict[str, Any]:
            input_args = {k: v for k, v in kwargs.items() if v is not None}
            if input_args:
                return {"status": "success", **input_args}
            return {"status": "success", "intent": func_name}

        params = [
            inspect.Parameter(p, inspect.Parameter.POSITIONAL_OR_KEYWORD, default=None)
            for p in param_names
        ]
        _api.__signature__ = inspect.Signature(params)  # type: ignore[attr-defined]
        _api.__name__ = func_name
        return _api

    def _wrap_with_signature(func: Any, func_name: str, param_names: List[str]) -> Any:
        """用声明的签名包装预生成函数，确保 EE 能按签名传参。"""
        params = [
            inspect.Parameter(p, inspect.Parameter.POSITIONAL_OR_KEYWORD, default=None)
            for p in param_names
        ]
        func.__signature__ = inspect.Signature(params)  # type: ignore[union-attr]
        func.__name__ = func_name
        return func

    if schema.intents:
        for intent in schema.intents:
            if not replace_existing and intent.name in engine.registry:
                logger.debug(f"[schema API] 跳过已注册函数: {intent.name}")
                continue
            display_slots = list(dict.fromkeys(
                list(intent.required_slots) + list(intent.optional_slots)
            ))
            if intent.name in _funcs:
                # 使用预生成的真实函数，并确保签名与 display_slots 一致
                func = _wrap_with_signature(_funcs[intent.name], intent.name, display_slots)
                logger.debug(f"[schema API] 注册预生成函数: {intent.name}({', '.join(display_slots)})")
            else:
                func = _make_stub_func(intent.name, display_slots)
                logger.debug(f"[schema API] 注册存根函数: {intent.name}({', '.join(display_slots)})")
            engine.registry[intent.name] = func
    else:
        if replace_existing or schema.service_name not in engine.registry:
            if schema.service_name in _funcs:
                func = _wrap_with_signature(_funcs[schema.service_name], schema.service_name, schema_slot_names)
            else:
                func = _make_stub_func(schema.service_name, schema_slot_names)
            engine.registry[schema.service_name] = func
            logger.debug(f"[schema API] 注册服务函数: {schema.service_name}({', '.join(schema_slot_names)})")

    logger.info(f"已基于外部 Schema 注册 API: {engine.list_functions()}")


